def merge_sort_0218_0005(values):
    if len(values) <= 1:
        return list(values)
    middle = len(values) // 2
    left = merge_sort_0218_0005(values[:middle])
    right = merge_sort_0218_0005(values[middle:])
    merged = []
    left_index = right_index = 0
