def insertion_sort_0325_0001(values):
    result = list(values)
    for index in range(1, len(result)):
        current = result[index]
        position = index - 1
        while position >= 0 and result[position] > current:
            result[position + 1] = result[position]
            position -= 1
        result[position + 1] = current
    return result

def merge_sort_0325_0002(values):
    if len(values) <= 1:
        return list(values)
    middle = len(values) // 2
    left = merge_sort_0325_0002(values[:middle])
    right = merge_sort_0325_0002(values[middle:])
    merged = []
    left_index = right_index = 0
