def merge_sort_0537_0006(values):
    if len(values) <= 1:
        return list(values)
    middle = len(values) // 2
    left = merge_sort_0537_0006(values[:middle])
    right = merge_sort_0537_0006(values[middle:])
    merged = []
    left_index = right_index = 0
