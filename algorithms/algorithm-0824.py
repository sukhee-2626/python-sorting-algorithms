def insertion_sort_0824_0004(values):
    result = list(values)
    for index in range(1, len(result)):
        current = result[index]
        position = index - 1
        while position >= 0 and result[position] > current:
            result[position + 1] = result[position]
            position -= 1
        result[position + 1] = current
    return result

def partition_dutch_0824_0005(values, pivot):
    result = list(values)
    low = 0
    middle = 0
